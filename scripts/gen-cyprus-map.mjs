// Generates src/lib/cyprus-map.ts: a single island outline (no internal borders)
// from Natural Earth 1:10m data, projected to a simple SVG coordinate space.
// Run: node scripts/gen-cyprus-map.mjs  (needs devDependencies world-atlas + topojson-client)
import fs from "node:fs";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const topo = require("topojson-client");
const world = require("world-atlas/countries-10m.json");

const BOX = { minLon: 32.2, maxLon: 34.65, minLat: 34.52, maxLat: 35.72 };
const inside = (g) => {
  let ok = false;
  const scan = (c) => (typeof c[0] === "number" ? c[0] > BOX.minLon && c[0] < BOX.maxLon && c[1] > BOX.minLat && c[1] < BOX.maxLat && (ok = true) : c.forEach(scan));
  scan(topo.feature(world, g).geometry.coordinates);
  return ok;
};
const island = topo.merge(world, world.objects.countries.geometries.filter(inside));

const W = 1000;
const kx = Math.cos((35.1 * Math.PI) / 180);
const scale = W / ((BOX.maxLon - BOX.minLon) * kx);
const H = Math.round((BOX.maxLat - BOX.minLat) * scale);
const px = (lon, lat) => [((lon - BOX.minLon) * kx * scale).toFixed(1), ((BOX.maxLat - lat) * scale).toFixed(1)];

const polys = island.type === "MultiPolygon" ? island.coordinates : [island.coordinates];
let d = "";
for (const poly of polys) {
  const ring = poly[0];
  // keep only reasonably sized rings (drop tiny islets)
  if (ring.length < 12) continue;
  d += "M" + ring.map(([lo, la]) => px(lo, la).join(",")).join("L") + "Z";
}

const out = `// AUTO-GENERATED by scripts/gen-cyprus-map.mjs from Natural Earth 1:10m (public domain).
export const CYPRUS_VIEWBOX = { w: ${W}, h: ${H} };
export const CYPRUS_BOX = ${JSON.stringify(BOX)};
export const CYPRUS_KX = ${kx};
export const CYPRUS_SCALE = ${scale};
export const CYPRUS_PATH = "${d}";
`;
fs.writeFileSync(new URL("../src/lib/cyprus-map.ts", import.meta.url), out);
console.log("viewBox", W, H, "path chars", d.length, "rings", polys.length);
